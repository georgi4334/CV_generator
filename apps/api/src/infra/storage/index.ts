import { createReadStream } from 'node:fs'
import { mkdir, rm, stat, writeFile } from 'node:fs/promises'
import { join, resolve } from 'node:path'
import type { Readable } from 'node:stream'

/**
 * Where uploaded files live. Local disk for development; an S3-compatible
 * implementation (Cloudflare R2) is added when the app is deployed (Step 17).
 */
export interface Storage {
  put(key: string, data: Buffer, contentType: string): Promise<void>
  get(key: string): Promise<Readable | null>
  remove(key: string): Promise<void>
}

export function createLocalStorage(directory: string): Storage {
  const root = resolve(directory)
  // Keys are generated by the API (uuid + extension); reject anything else.
  const pathFor = (key: string) => {
    if (!/^[a-z0-9-]+\.[a-z0-9]+$/i.test(key)) throw new Error(`Invalid storage key: ${key}`)
    return join(root, key)
  }

  return {
    async put(key, data) {
      await mkdir(root, { recursive: true })
      await writeFile(pathFor(key), data)
    },
    async get(key) {
      const path = pathFor(key)
      try {
        await stat(path)
      } catch {
        return null
      }
      return createReadStream(path)
    },
    async remove(key) {
      await rm(pathFor(key), { force: true })
    },
  }
}
